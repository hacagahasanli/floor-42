import { launch, open, sdk, shot, save, fightUntilResult, ftStats, ftTake } from './lib.mjs';
const browser = await launch();
const res = {};
const { ctx, page, frame, log } = await open(browser, { w: 1280, h: 720 });
const f = frame();
await f.waitForSelector('[data-testid="home"]');
await page.waitForTimeout(1000);
const t0 = await f.evaluate(() => performance.now());
await f.click('[data-testid="open-2p"]', { force: true });
await page.waitForTimeout(1000);
await page.keyboard.press('KeyF'); await page.waitForTimeout(200); await page.keyboard.press('Semicolon');
await page.waitForTimeout(4000);
await shot(page, 's6-2p-card');
await page.keyboard.press('KeyF'); await page.waitForTimeout(200); await page.keyboard.press('Semicolon');
res.started = await f.waitForFunction(() => (window.__sdk || []).some((x) => x[0] === 'gameplayStart'), null, { timeout: 20000 }).then(() => true, () => false);
await ftTake(f);
// P2 holds left and shoots via a parallel interval of key presses
const p2 = setInterval(() => { page.keyboard.press('Semicolon').catch(() => {}); }, 400);
const t = await fightUntilResult(page, f, { timeoutMs: 230000, keys: { l: 'KeyA', r: 'KeyD', up: 'KeyW', fire: 'KeyF' } });
clearInterval(p2);
res.matchMs = t; res.ft = ftStats(await ftTake(f));
await page.waitForTimeout(3500);
await shot(page, 's6-2p-result');
res.resultText = (await f.evaluate(() => document.body.innerText)).slice(0, 300);
const n = (await sdk(f)).filter((x) => x[0] === 'gameplayStart').length;
await page.keyboard.press('Enter');
await page.waitForTimeout(2500);
await shot(page, 's6-2p-after-enter');
await page.keyboard.press('KeyF'); await page.waitForTimeout(200); await page.keyboard.press('Semicolon');
res.rematch = await f.waitForFunction((n) => (window.__sdk || []).filter((x) => x[0] === 'gameplayStart').length > n, n, { timeout: 20000 }).then(() => true, () => false);
await page.waitForTimeout(1200);
await shot(page, 's6-2p-rematch');
res.sdk = await sdk(f); res.t0 = t0;
res.errors = log.pageerrors.map((e) => e.msg); res.console = log.console;
save('s6', res);
console.log(JSON.stringify(res, null, 1));
await browser.close();
