/**
 * Exports the Pewfield identity (docs/collab/CREATIVE/brand, logo concept A) into public/ and portal/static/:
 * wordmark + emblem + mono SVGs, favicons, apple-touch icon, manifest icons, OG image, and the inline wordmark module.
 * Run: python3-outlined SVGs are made first (tools/brand/outline.py), so this needs `fonttools brotli` and node_modules (sharp).
 *   node tools/brand/export-pewfield.mjs
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import sharp from 'sharp';

const SRC = 'docs/collab/CREATIVE/brand/svg/';
const tmp = path.join(tmpdir(), 'pewfield-brand');
mkdirSync(tmp, { recursive: true });
const outline = (name, extra = []) => {
  const out = path.join(tmp, name);
  execFileSync('python3', ['tools/brand/outline.py', SRC + name, out, ...extra]);
  return readFileSync(out, 'utf8');
};
const wordmark = outline('a-wordmark.svg');
const icon = outline('a-icon.svg');
const burst = outline('a-mark.svg', ['--no-text']);
const GRAPE = '#3B1F6B';
const mono = wordmark.replace(/fill="#(FF7A2F|FFC83D|FFE38A)"/g, `fill="${GRAPE}"`).replace(/ opacity="\.\d+"/g, '');
const clean = (s) => s.replace('<svg ', '<svg role="img" aria-label="Pewfield" ');

// Apple touch icon and maskable are full-bleed squares (the OS rounds or masks them).
const square = icon.replace(/rx="(112|104)"/g, 'rx="0"').replace(/<rect x="10"[^>]*\/>/, '');
const maskable = (() => {
  const i = square.indexOf('<defs><clipPath id="c');
  return square.slice(0, i) + '<g transform="translate(256 256) scale(.74) translate(-256 -256)">' + square.slice(i, -6) + '</g></svg>';
})();

const png = (svg, size, file) => sharp(Buffer.from(svg), { density: 384 }).resize(size, size).png({ compressionLevel: 9 }).toFile(file);
const ico = async (files) => {
  const bufs = await Promise.all(files.map(([svg, s]) => sharp(Buffer.from(svg), { density: 384 }).resize(s, s).png().toBuffer()));
  const head = Buffer.alloc(6 + 16 * bufs.length);
  head.writeUInt16LE(1, 2);
  head.writeUInt16LE(bufs.length, 4);
  let off = head.length;
  bufs.forEach((b, i) => {
    const s = files[i][1];
    head.writeUInt8(s, 6 + i * 16); head.writeUInt8(s, 7 + i * 16); head.writeUInt16LE(1, 10 + i * 16); head.writeUInt16LE(32, 12 + i * 16);
    head.writeUInt32LE(b.length, 14 + i * 16); head.writeUInt32LE(off, 18 + i * 16);
    off += b.length;
  });
  return Buffer.concat([head, ...bufs]);
};

for (const dir of ['public', 'portal/static']) {
  mkdirSync(`${dir}/brand`, { recursive: true });
  writeFileSync(`${dir}/brand/logo.svg`, clean(wordmark));
  writeFileSync(`${dir}/brand/logo-light.svg`, clean(wordmark));
  writeFileSync(`${dir}/brand/logo-mono.svg`, clean(mono));
  writeFileSync(`${dir}/brand/emblem.svg`, clean(burst));
  writeFileSync(`${dir}/favicon.svg`, burst);
  await png(burst, 16, `${dir}/favicon-16.png`);
  await png(burst, 32, `${dir}/favicon-32.png`);
  writeFileSync(`${dir}/favicon.ico`, await ico([[burst, 16], [burst, 32], [icon, 48]]));
  await png(square, 180, `${dir}/apple-touch-icon.png`);
}
mkdirSync('public/icons', { recursive: true });
await png(icon, 512, 'public/icons/icon-512.png');
await png(icon, 192, 'public/icons/icon-192.png');
await png(icon, 48, 'public/icons/icon-48.png');
await png(maskable, 512, 'public/icons/maskable-512.png');

// The inline wordmark (one source for the Home screen and the boot screen): the SVG's inner markup, no root element.
const inner = wordmark.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
writeFileSync(
  'src/components/fieldday/wordmarkArt.ts',
  `/** GENERATED by tools/brand/export-pewfield.mjs from the Creative Director's a-wordmark.svg (text already converted to paths). Do not edit. */\nexport const WORDMARK_VIEWBOX = '0 0 1200 520';\nexport const WORDMARK_INNER = ${JSON.stringify(inner)};\n`,
);

// OG image 1200x630: sky tile with the wordmark centred.
const wm = await sharp(Buffer.from(wordmark), { density: 192 }).resize({ height: 420 }).png().toBuffer();
const bg = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630"><defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#4CB8FF"/><stop offset="1" stop-color="#A9DDF7"/></linearGradient></defs><rect width="1200" height="630" fill="url(#g)"/><rect y="520" width="1200" height="110" fill="#F2C98A"/></svg>`);
await sharp(bg).composite([{ input: wm, gravity: 'centre' }]).jpeg({ quality: 88, mozjpeg: true }).toFile('public/og.jpg');
console.log('ok');
