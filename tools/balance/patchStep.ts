/**
 * Builds tools/balance/.gen/step.ts: the real src/game/sim/step.ts with five anchored trait hooks.
 * Every anchor must match exactly once, or this throws: if step.ts changes, the harness fails loudly
 * instead of simulating a stale copy. src/ is never written.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, '../../src/game/sim/step.ts');
export const GEN = join(here, '.gen/step.ts');

const PATCHES: [string, string, string][] = [
  // 1. Trait timers tick with the others; 2. Tea Break: Ormo's own regen delay.
  [
    'tick+regen',
    'f.sinceHit += DT;\n  if (f.respawn <= 0 && f.hp > 0 && f.sinceHit >= RULES.regenAfter)',
    'TRAITS.tick(f);\n  f.sinceHit += DT;\n  if (f.respawn <= 0 && f.hp > 0 && f.sinceHit >= TRAITS.regenAfter(f))',
  ],
  // 3. Sugar Rush: top run speed.
  ['speed', 'const maxSpeed = c.speed * GUNS', 'const maxSpeed = c.speed * TRAITS.speedMul(f) * GUNS'],
  // 4. Sugar Rush trigger: after damage lands.
  ['onHit', 'if (hit.damage > 0) target.sinceHit = 0;', 'if (hit.damage > 0) target.sinceHit = 0;\n  TRAITS.onHit(state, target, hit);'],
  // 5. Packed Extra: the gun Tavo picks up.
  ['pickup', 'else f.weapon = newWeapon(p.kind);', 'else f.weapon = TRAITS.pickupWeapon(f, newWeapon(p.kind));'],
  // 5b. Packed Extra: a bigger magazine has to reload to its own size, not the gun table's.
  ['reload-take', 'const take = Math.min(g.mag - w.mag, w.reserve);', 'const take = Math.min(TRAITS.magSize(w) - w.mag, w.reserve);'],
  ['reload-full', 'if (w.mag >= g.mag || w.reserve <= 0) return;', 'if (w.mag >= TRAITS.magSize(w) || w.reserve <= 0) return;'],
  // 6. Leapfrog: after both fighters moved.
  [
    'afterMove',
    'for (const f of state.fighters) updateFighter(state, f, inputs[f.id] ?? EMPTY_INPUT);',
    'for (const f of state.fighters) updateFighter(state, f, inputs[f.id] ?? EMPTY_INPUT);\n  TRAITS.afterMove(state);',
  ],
];

export const buildPatchedStep = () => {
  let s = readFileSync(SRC, 'utf8');
  s = s.replaceAll("from './constants'", "from '../../../src/game/sim/constants'").replaceAll("from './types'", "from '../../../src/game/sim/types'");
  s = "import { TRAITS } from '../traits';\n" + s;
  for (const [name, from, to] of PATCHES) {
    const n = s.split(from).length - 1;
    if (n !== 1) throw new Error(`patchStep: anchor "${name}" matched ${n} times; update tools/balance/patchStep.ts`);
    s = s.replace(from, to);
  }
  s = '// GENERATED by tools/balance/patchStep.ts from src/game/sim/step.ts. Do not edit.\n' + s;
  mkdirSync(dirname(GEN), { recursive: true });
  writeFileSync(GEN, s);
  return GEN;
};

if (process.argv[1] === fileURLToPath(import.meta.url)) console.log('wrote', buildPatchedStep());
